export function catSays(state: SnowState) {
  const day = Number(state.today.slice(-2));
  const count = state.completed_days || 0;
  if (state.phase === 'upcoming') return catLines.before[day % catLines.before.length];
  if (state.phase === 'finished') return catLines.finale[3];
  if (state.phase === 'shop_only') return catLines.finale[2];
  if (count === 31) return catLines.finale[0];
  if (count >= 26) return catLines.finale[1];
  if (state.progress.days[state.today]?.game) return catLines.done[day % catLines.done.length];
  const total = state.world?.total || 0;
  const stageLines = [
    [1750, 5],
    [1500, 4],
    [1300, 3],
    [1000, 2],
    [700, 1],
    [100, 0],
  ];
  if (day % 3 === 0) {
    const stage = stageLines.find(([threshold]) => total >= threshold);
    if (stage) return catLines.stages[stage[1]];
  }
  return catLines.chapters[Math.min(3, Math.floor((day - 1) / 7))][day % 6];
}
