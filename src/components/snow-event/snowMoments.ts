export function momentFor(state: SnowState, day?: number) {
  const number = day ?? (state.today.startsWith('2026-12-') ? Number(state.today.slice(-2)) : 0);
  if (number < 1 || number > 31 || `2026-12-${String(number).padStart(2,'0')}` > state.today) return null;
  const [name, text, zone] = momentNames[number - 1];
  const positions = { data: [35, 72], plaza: [67, 86], workshop: [77, 74], orbit: [23, 86] } as const;
  return { day: number, name, text, zone, x: positions[zone][0], y: positions[zone][1] };
}
